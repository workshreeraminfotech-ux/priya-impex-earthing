const signatureImages = import.meta.glob('../assets/signture products/**/*.{png,PNG,jpg,JPG,jpeg,JPEG,webp,WEBP}', {
  eager: true,
  import: 'default'
});

// Build comprehensive pre-indexed lookup cache for robust image matching
function normalizeImageKey(str) {
  if (!str) return '';
  return String(str)
    .toLowerCase()
    .replace(/\\/g, '/')
    .split('/')
    .pop()
    .replace(/^\d+[\s._-]+/, '') // strip numbers like "1 ", "10."
    .replace(/\.[^.]+$/, '') // strip file extension
    .replace(/[^a-z0-9]/g, ''); // strip symbols
}

const imageLookupMap = new Map();

for (const [filePath, fileUrl] of Object.entries({ ...productImages, ...signatureImages })) {
  if (!fileUrl) continue;
  
  // 1. Exact path
  imageLookupMap.set(filePath, fileUrl);
  imageLookupMap.set(filePath.toLowerCase(), fileUrl);
  
  // 2. Exact filename with extension
  const filename = filePath.split('/').pop();
  imageLookupMap.set(filename, fileUrl);
  imageLookupMap.set(filename.toLowerCase(), fileUrl);
  
  // 3. Clean alphanumeric key (numbers stripped)
  const cleanKey = normalizeImageKey(filePath);
  if (cleanKey && !imageLookupMap.has(cleanKey)) {
    imageLookupMap.set(cleanKey, fileUrl);
  }
}

// Fallback image in case of missing asset
const fallbackImage = Object.values(signatureImages)[0] || Object.values(productImages)[0] || '';

// Helper function to resolve product image from relative path or filename
export function getProductImage(relPath) {
  if (!relPath) return fallbackImage;
  
  // Direct path lookup
  if (imageLookupMap.has(relPath)) return imageLookupMap.get(relPath);
  
  const lower = relPath.toLowerCase();
  if (imageLookupMap.has(lower)) return imageLookupMap.get(lower);
  
  // Filename lookup
  const filename = relPath.split('/').pop();
  if (imageLookupMap.has(filename)) return imageLookupMap.get(filename);
  if (imageLookupMap.has(filename.toLowerCase())) return imageLookupMap.get(filename.toLowerCase());
  
  // Clean alphanumeric lookup
  const clean = normalizeImageKey(relPath);
  if (imageLookupMap.has(clean)) return imageLookupMap.get(clean);
  
  // Substring search fallback
  for (const [key, url] of imageLookupMap.entries()) {
    if (clean && clean.length >= 4 && (key.includes(clean) || clean.includes(key))) {
      return url;
    }
  }
  
  return fallbackImage;
}

